@app.post("/feedback")
async def post_feedback(body: FeedbackBody):
    """Recebe um voto 👍/👎 do utilizador e persiste no grafo Neo4j.

    Usa rag_search(question, k=5) pra aproximar quais chunks foram usados
    na resposta (Option B: re-run da questão como proxy dos chunks servidos).
    Cria :Feedback node e incrementa feedback_positive / feedback_negative
    nos :Chunk nodes relevantes.
    """
    import uuid as _uuid

    from rag import get_rag

    if body.vote not in ("up", "down"):
        raise HTTPException(status_code=422, detail="vote must be 'up' or 'down'")

    try:
        rag = get_rag()

        # Aproxima os chunks usados re-rodando hybrid_search na questão
        hits = rag.hybrid_search(body.question, k=5)
        chunk_ids = [h.id for h in hits if h.id]

        rag.save_feedback(
            feedback_id=body.feedbackId or _uuid.uuid4().hex,
            conversation_id=body.conversationId,
            message_id=body.messageId,
            question=body.question,
            answer=body.answer,
            vote=body.vote,
            chunk_ids=chunk_ids,
        )

        return {
            "ok": True,
            "vote": body.vote,
            "chunks_updated": len(chunk_ids),
        }
    except Exception as e:  # noqa: BLE001
        raise HTTPException(500, f"Erro ao salvar feedback: {e}")


