@app.post("/chat")
async def chat(body: ChatBody):
    graph = _get_graph()
    reset_steps()
    try:
        result = await graph.ainvoke(
            {"messages": [_build_user_message(body)]},
            config=_config_for(body),
        )
        last = result["messages"][-1]

        content = last.content
        if isinstance(content, list):
            content = "".join(
                b.get("text", "") if isinstance(b, dict) else str(b)
                for b in content
            )
        # If the graph paused at a clarify interrupt, the last message is still
        # the user HumanMessage (no AI reply yet). Detect and surface the question.
        from langchain_core.messages import HumanMessage as _HumanMessage
        if isinstance(last, _HumanMessage):
            state = await graph.aget_state(_config_for(body))
            interrupts = [
                intr.value
                for task in (state.tasks or [])
                for intr in (getattr(task, "interrupts", None) or [])
            ]
            if interrupts:
                intr = interrupts[0]
                opts = ", ".join(o["label"] for o in (intr.get("options") or []))
                content = f"{intr.get('question', 'Por favor, seja mais específico.')} ({opts})"
            else:
                content = ""
        return {"reply": content}
    finally:
        print(turn_summary())


def _streaming_response(generator: AsyncIterator[bytes]) -> StreamingResponse:
    """Wrap an async bytes generator into a StreamingResponse with SSE headers."""
    return StreamingResponse(
        generator,
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache, no-transform",
            "X-Accel-Buffering": "no",
            "Connection": "keep-alive",
        },
    )

_suggest_llm = None


def _get_suggest_llm():
    """Lazy singleton LLM used only for follow-up suggestions."""
    global _suggest_llm
    if _suggest_llm is None:
        from langchain_google_genai import ChatGoogleGenerativeAI
        _suggest_llm = ChatGoogleGenerativeAI(
            model=config.gemini.model,
            google_api_key=config.gemini.api_key,
            temperature=config.gemini.temperature,
        )
    return _suggest_llm


async def _suggest_followups(question: str, answer: str) -> list[str]:
    """Gera 3 perguntas de seguimento curtas com sanitização rigorosa."""
    if not answer.strip():
        return []

    prompt = (
        "Com base na pergunta e resposta abaixo, sugere 3 perguntas de seguimento "
        "curtas (máx. 5 palavras cada). Responde APENAS com as 3, uma por linha, "
        "sem numeração, sem aspas, sem marcadores.\n\n"
        f"Pergunta: {question}\nResposta: {answer[:1500]}"
    )

    try:
        llm = _get_suggest_llm()
        resp = await llm.ainvoke(prompt)

        # Normaliza o conteúdo para string
        content = resp.content
        if isinstance(content, list):
            content = " ".join([str(b.get("text", "")) for b in content if isinstance(b, dict)])

        lines = []
        for line in content.splitlines():
            clean_line = re.sub(r'^\d+[\.\)]\s*', '', line).strip(" -•*\"'")
            if clean_line:
                lines.append(clean_line)

        return lines[:3]

    except Exception as e:
        print(f"[suggest] Erro na geração: {e}")
        return []



async def _run_graph_stream(
    graph,
    graph_input,
    run_config: dict,
    conversation_id: str,
    request: Optional[Request] = None,
    question: str = "",
):
    """Shared SSE generator for both /chat/stream and /chat/resume.

    Streams AG-UI events from a LangGraph run. After the astream loop ends,
    checks the graph state for a pending interrupt and emits an INTERRUPT event
    so the frontend can render interactive option cards.
    """
    run_id = str(uuid.uuid4())
    current_msg_id: str | None = None
    current_agent: str | None = None
    answer_buf: list[str] = []   # accumulates assistant text for follow-up suggestions

    tool_q: asyncio.Queue = asyncio.Queue()
    ctx_token = _tool_event_queue.set(tool_q)

    def _drain_tool_queue():
        events = []
        while not tool_q.empty():
            events.append(tool_q.get_nowait())
        return events

    yield _sse({"type": "RUN_STARTED", "runId": run_id, "threadId": conversation_id})

    try:
        async for chunk, metadata in graph.astream(
            graph_input,
            config=run_config,
            stream_mode="messages",
        ):
            if request and await request.is_disconnected():
                break

            node = (metadata or {}).get("langgraph_node")
            if node in ("supervisor", "clarify"):
                continue

            # Emit which agent is now active so the client can show an indicator
            # (and render a distinct crisis card when node == "crisis").

            if node and node != current_agent:
                if current_agent:
                    # AG-UI spec: close the previous lifecycle step before opening a new one.
                    yield _sse({"type": "STEP_FINISHED", "stepName": current_agent})
                current_agent = node
                # AG-UI spec: a lifecycle step -> STEP_STARTED with stepName.
                yield _sse({"type": "STEP_STARTED", "stepName": node})

            # Always flush tool events before any text check so rag_search
            # badges (from faq_agent) appear even when we suppress the text.
            for ev in _drain_tool_queue():
                yield _sse(ev)

            raw = getattr(chunk, "content", "") or ""
            if not isinstance(raw, str):
                try:
                    delta = "".join(
                        p.get("text", "")
                        for p in raw
                        if isinstance(p, dict) and p.get("type") != "thinking"
                    )
                except Exception:
                    delta = ""
            else:
                delta = raw

            if delta.startswith("FAQ_MISS"):
                continue

            if delta:
                if current_msg_id is None:
                    current_msg_id = str(uuid.uuid4())
                    yield _sse({
                        "type": "TEXT_MESSAGE_START",
                        "messageId": current_msg_id,
                        "role": "assistant",
                    })
                answer_buf.append(delta)
                yield _sse({
                    # AG-UI spec: streaming text chunk is TEXT_MESSAGE_CONTENT.
                    "type": "TEXT_MESSAGE_CONTENT",
                    "messageId": current_msg_id,
                    "delta": delta,
                })

        for ev in _drain_tool_queue():
            yield _sse(ev)

        if current_msg_id:
            yield _sse({"type": "TEXT_MESSAGE_END", "messageId": current_msg_id})

        if current_agent:
            # AG-UI spec: close the last lifecycle step once the run's graph loop ends.
            yield _sse({"type": "STEP_FINISHED", "stepName": current_agent})

        # ── Check for pending interrupt (e.g. clarify node paused the graph) ──
        try:
            state = await graph.aget_state(run_config)
            all_interrupts = [
                intr.value
                for task in (state.tasks or [])
                for intr in (getattr(task, "interrupts", None) or [])
            ]
            if all_interrupts:
                intr_val = all_interrupts[0]
                print(f"[server] interrupt detected: {intr_val}")
                # AG-UI spec: app-specific events go through CUSTOM (name + value).
                yield _sse({"type": "CUSTOM", "name": "interrupt", "value": intr_val})
        except Exception as exc:  # noqa: BLE001
            print(f"[server] aget_state error: {exc}")
            all_interrupts = []

        # ── Contextual follow-up suggestions (only on a real answer) ──────────
        if not all_interrupts and answer_buf:
            items = await _suggest_followups(question, "".join(answer_buf))
            if items:
                yield _sse({"type": "CUSTOM", "name": "suggestions", "value": {"items": items}})

        yield _sse({"type": "RUN_FINISHED", "runId": run_id, "threadId": conversation_id})

    except asyncio.CancelledError:
        raise
    except Exception as exc:  # noqa: BLE001
        for ev in _drain_tool_queue():
            yield _sse(ev)
        if current_msg_id:
            yield _sse({"type": "TEXT_MESSAGE_END", "messageId": current_msg_id})
        if current_agent:
            yield _sse({"type": "STEP_FINISHED", "stepName": current_agent})
        yield _sse({"type": "RUN_ERROR", "runId": run_id, "message": str(exc)})
    finally:
        _tool_event_queue.reset(ctx_token)
        print(turn_summary())


@app.post("/chat/stream")
async def chat_stream(body: ChatBody, request: Request):
    graph = _get_graph()
    reset_steps()
    run_config = _config_for(body)
    user_msg = _build_user_message(body)
    question = body.messages[-1].content if body.messages else ""

    return _streaming_response(
        _run_graph_stream(graph, {"messages": [user_msg]}, run_config, body.conversationId, request, question)
    )


@app.post("/chat/resume")
async def chat_resume(body: ResumeBody, request: Request):
    """Resume a graph that was paused at an interrupt (e.g. clarify node).

    The frontend sends the value selected by the user; we pass it to the graph
    via Command(resume=value) so the clarify_node can receive it and continue.
    """
    from langgraph.types import Command

    graph = _get_graph()
    reset_steps()
    run_config = _config_for(body)

    return _streaming_response(
        _run_graph_stream(graph, Command(resume=body.value), run_config, body.conversationId, request)
    )


@app.post("/upload")
async def upload(file: UploadFile = File(...)):
    """
    Compat: o react-chat-ui usa /upload pra anexos genericos.
    Apenas le e retorna metadata. Nao indexa.
    """
    size = 0
    while chunk := await file.read(1024 * 64):
        size += len(chunk)
    return {
        "id": file.filename or "upload",
        "filename": file.filename,
        "content_type": file.content_type,
        "size": size,
        "note": "Use /documents/upload para indexar no RAG.",
    }


@app.post("/documents/upload")
async def documents_upload(file: UploadFile = File(...)):
    """
    Upload de documentos que devem ENTRAR no RAG (uploads persistentes).

    Aceita: .pdf, .docx, .txt, .md (texto extraido e indexado);
            imagens sao salvas mas nao indexadas (qwen2.5 nao e multimodal).

    Retorna: { id, filename, kind, chunks, size, note? }
    """
    import uuid as _uuid
    from pathlib import Path

    from extract import extract
    from rag import get_rag

    data = await file.read()
    size = len(data)

    # 1) Salva o original em uploads/ (mesmo que nao seja indexado)
    uploads_dir = Path(__file__).parent / "uploads"
    uploads_dir.mkdir(exist_ok=True)
    doc_id = _uuid.uuid4().hex
    safe_name = (file.filename or doc_id).replace("/", "_").replace("\\", "_")
    saved_path = uploads_dir / f"{doc_id}__{safe_name}"
    saved_path.write_bytes(data)

    # 2) Extrai texto conforme tipo
    extracted = extract(data, file.filename or "", file.content_type)

    # 3) Indexa no RAG se houver texto
    chunks = 0
    note = extracted.note
    if extracted.text.strip():
        try:
            rag = get_rag()
            chunks = rag.index_text(
                extracted.text,
                source=f"upload://{safe_name}",
                kind="upload",
                extra_metadata={
                    "doc_id": doc_id,
                    "filename": safe_name,
                    "content_type": file.content_type or "",
                },
            )
        except Exception as e:
            note = f"Texto extraido mas indexacao falhou: {e}"

    return {
        "id": doc_id,
        "filename": file.filename,
        "saved_as": str(saved_path.name),
        "kind": extracted.kind,
        "content_type": file.content_type,
        "size": size,
        "chunks": chunks,
        "note": note,
    }


